// Build image array: 3-4 images cycling through the pool from an offset
function imgs(offset, count = 3) {
  return Array.from({ length: count }, (_, i) => {
    const url = IMG_POOL[(offset + i) % IMG_POOL.length];
    return { public_id: `rentify/seed/${offset}_${i}`, secure_url: url };
  });
}

// Deterministic status distribution: 80% APPROVED, 15% PENDING, 5% REJECTED
function getStatus(pos) {
  const r = (pos * 97 + 31) % 100;
  if (r < 80) return "APPROVED";
  if (r < 95) return "PENDING";
  return "REJECTED";
}

