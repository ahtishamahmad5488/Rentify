// ─── Build full property document from spec ────────────────────────────────
function buildProperty(spec, idx, ownerIds) {
  const [
    imgOffset,
    ownerIdx,
    title,
    description,
    city,
    area,
    address,
    lat,
    lng,
    price,
    propertyType,
    totalRooms,
    availableRooms,
    genderType,
    facilities,
  ] = spec;

  const s = getStatus(idx);
  const imgCount = 3 + (idx % 2 === 0 ? 1 : 0); // 3 or 4 images alternating

  return {
    owner: ownerIds[ownerIdx % ownerIds.length],
    title,
    description,
    city,
    area,
    address,
    latitude: parseFloat(lat.toFixed(6)),
    longitude: parseFloat(lng.toFixed(6)),
    location: {
      type: "Point",
      coordinates: [parseFloat(lng.toFixed(6)), parseFloat(lat.toFixed(6))],
    },
    price,
    propertyType,
    totalRooms,
    availableRooms,
    genderType,
    facilities,
    images: imgs(imgOffset, imgCount),
    isAvailable: s === "APPROVED",
    views:
      s === "APPROVED"
        ? Math.floor((idx * 137 + 23) % 490) + 10
        : Math.floor((idx * 17) % 20),
    status: s,
    isDeleted: false,
  };
}

// ─── Main seeder ──────────────────────────────────────────────────────────────
async function seed() {
  await connectDB();

  // ── Clear mode ───────────────────────────────────────────────────────────
  if (CLEAR) {
    console.log("\n🗑  SEED_CLEAR=true — removing seeded data...");
    const seededLandlords = await Landlord.find({
      email: { $regex: SEED_TAG + "$" },
    }).select("_id");
    const ids = seededLandlords.map((l) => l._id);

    if (ids.length > 0) {
      // Bypass the soft-delete pre-find middleware by using deleteMany directly on the collection
      const propResult = await Property.collection.deleteMany({
        owner: { $in: ids },
      });
      const landlordResult = await Landlord.deleteMany({ _id: { $in: ids } });
      console.log(`   ✅ Deleted ${propResult.deletedCount} properties`);
      console.log(`   ✅ Deleted ${landlordResult.deletedCount} landlords`);
    } else {
      console.log("   ℹ  No seeded records found to clear.");
    }

    if (process.env.SEED_CLEAR_ONLY === "true") {
      await mongoose.disconnect();
      process.exit(0);
    }
  }

  // ── Insert Landlords ─────────────────────────────────────────────────────
  console.log("\n👤 Creating landlords...");

  // Check and skip already-existing seeded emails
  const existingEmails = new Set(
    (
      await Landlord.find({ email: { $regex: SEED_TAG + "$" } }).select("email")
    ).map((l) => l.email),
  );

  const newLandlordDocs = LANDLORD_DATA.filter(
    (l) => !existingEmails.has(l.email),
  ).map((l) => ({
    name: l.name,
    email: l.email,
    password: "Seed@1234",
    phone: l.phone,
    cnic: l.cnic,
    businessAddress: l.businessAddress,
    role: "landlord",
    isVerified: true,
    isActive: true,
    profileImage: { public_id: null, secure_url: null },
  }));

  let insertedLandlords = [];

  if (newLandlordDocs.length > 0) {
    // Use Mongoose model to trigger pre-save password hashing
    insertedLandlords = await Landlord.insertMany(newLandlordDocs);
    console.log(`   ✅ Inserted ${insertedLandlords.length} new landlords`);
  } else {
    console.log("   ℹ  All landlords already exist — skipping.");
  }

  // Fetch all seeded landlord IDs (existing + newly inserted)
  const allSeededLandlords = await Landlord.find({
    email: { $regex: SEED_TAG + "$" },
  }).select("_id");
  const ownerIds = allSeededLandlords.map((l) => l._id);

  if (ownerIds.length === 0) {
    console.error("❌ No seeded landlords found. Aborting property insertion.");
    await mongoose.disconnect();
    process.exit(1);
  }

  // ── Insert Properties ────────────────────────────────────────────────────
  console.log("\n🏠 Inserting properties...");

  const propertyDocs = SPECS.map((spec, idx) =>
    buildProperty(spec, idx, ownerIds),
  );

  await Property.collection.insertMany(propertyDocs);

  const total = propertyDocs.length;
  const approved = propertyDocs.filter((p) => p.status === "APPROVED").length;
  const pending = propertyDocs.filter((p) => p.status === "PENDING").length;
  const rejected = propertyDocs.filter((p) => p.status === "REJECTED").length;

  console.log(`   ✅ Inserted ${total} properties`);
  console.log(
    `      APPROVED: ${approved} | PENDING: ${pending} | REJECTED: ${rejected}`,
  );

  // ── Sample output ────────────────────────────────────────────────────────
  const sample = propertyDocs.find((p) => p.status === "APPROVED");
  console.log("\n📦 Sample property:");
  console.log(
    JSON.stringify(
      {
        title: sample.title,
        city: sample.city,
        area: sample.area,
        price: sample.price,
        propertyType: sample.propertyType,
        status: sample.status,
        latitude: sample.latitude,
        longitude: sample.longitude,
        facilities: sample.facilities,
        images: sample.images.length + " images",
      },
      null,
      2,
    ),
  );

  // ── Cities summary ───────────────────────────────────────────────────────
  const citySummary = {};
  propertyDocs.forEach((p) => {
    citySummary[p.city] = (citySummary[p.city] || 0) + 1;
  });
  console.log("\n📍 By city:", citySummary);

  console.log("\n✅ Seeding complete!\n");
  await mongoose.disconnect();
  process.exit(0);
}

seed().catch((err) => {
  console.error("❌ Seeder error:", err.message);
  process.exit(1);
});
